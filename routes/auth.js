// Password reset confirm
router.post('/reset-password/confirm', rateLimit, async (req, res) => {
    try {
        const email = str(req.body.email, 254);
        const code = str(req.body.code, 10);
        const newPassword = req.body.newPassword;
        if (!email || !code || !newPassword) {
            return res.status(400).json({ error: 'E-Mail, Code und neues Passwort werden benötigt.' });
        }
        if (!validPassword(newPassword)) {
            return res.status(400).json({ error: `Das Passwort muss mindestens ${MIN_PASSWORD_LENGTH} Zeichen lang sein.` });
        }
        const user = await User.findOne({ where: { email } });
        if (!user) {
            return res.status(400).json({ error: 'Ungültiger Code oder E-Mail.' });
        }

        const err = await consumeCode(user, 'resetCode', 'resetCodeExpiresAt', code);
        if (err) return res.status(400).json({ error: err });

        user.password_hash = await bcrypt.hash(newPassword, 10);
        user.isActive = true; // Automatically mark account as active since they proved ownership of the email
        await user.save();
        await destroyOtherSessions(sequelize, user.id);
        return res.json({ ok: true });
    } catch (err) {
        console.error('Reset confirm error', err);
        return res.status(500).json({ error: 'Internal Server Error' });
    }
});

