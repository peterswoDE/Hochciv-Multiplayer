const rateLimitLib = require('express-rate-limit');

// Use express-rate-limit for robust IP limiting against brute-force attacks
const rateLimit = rateLimitLib({
    windowMs: 60 * 1000, // 1 minute
    max: 15,
    message: { error: 'Zu viele Anfragen. Bitte versuche es später erneut.' },
    standardHeaders: true,
    legacyHeaders: false
});

/** Finish a login: the session id is regenerated by passport (session fixation). */
function finishLogin(req, res, user) {
    req.login(user, (err) => {
        if (err) return res.status(500).json({ error: 'Login failed' });
        return res.json(userJson(user));
    });
}

/** The user waiting for the second factor, or null. */
async function pendingUser(req) {
    const id = req.session.mfaPendingUserId;
    if (!id) return null;
    const user = await User.findByPk(id);
    return user && !user.isBanned ? user : null;
}

// Register endpoint
router.post('/register', rateLimit, async (req, res) => {
    try {
        if (!serverState.state.registrationEnabled) {
            return res.status(403).json({ error: 'Registrierungen sind derzeit deaktiviert.' });
        }
        const username = str(req.body.username, 30);
        const email = str(req.body.email, 254);
        const password = req.body.password;
        if (!username || !email || !password) {
            return res.status(400).json({ error: 'Username, Email and Password are required.' });
        }
        if (!USERNAME_RE.test(username)) {
            return res.status(400).json({ error: 'Benutzername: 3–30 Zeichen, nur Buchstaben, Ziffern, _ und -.' });
        }
        if (!EMAIL_RE.test(email)) return res.status(400).json({ error: 'Ungültige E-Mail-Adresse.' });
        if (!validPassword(password)) {
            return res.status(400).json({ error: `Das Passwort muss mindestens ${MIN_PASSWORD_LENGTH} Zeichen lang sein.` });
        }
        const existingUser = await User.findOne({
            where: { [Op.or]: [{ username }, { email }] }
        });
        if (existingUser) {
            return res.status(400).json({ error: 'Username or Email already exists.' });
        }
        const password_hash = await bcrypt.hash(password, 10);
        const activationCode = generateCode();

        await User.create({
            username,
            email,
            password_hash,
            isActive: false,
            activationCode,
            activationCodeExpiresAt: new Date(Date.now() + 60 * 60 * 1000) // 1 hour
        });

        const text = `Dein Hochciv Aktivierungscode lautet: ${activationCode}`;
        await sendMail(email, 'Hochciv Account aktivieren', text, text);

        return res.json({ ok: true, message: 'Activation code sent' });
    } catch (err) {
        console.error('Register error', err);
        res.status(500).json({ error: 'Internal Server Error' });
    }
});

// Activate endpoint
router.post('/activate', rateLimit, async (req, res) => {
    try {
        const username = str(req.body.username, 30);
        const code = str(req.body.code, 10);
        if (!username || !code) return res.status(400).json({ error: 'Missing code' });

        const user = await User.findOne({ where: { username } });
        if (!user) return res.status(404).json({ error: 'User not found' });
        if (user.isActive) return res.status(400).json({ error: 'Already activated' });
        if (user.isBanned) return res.status(403).json({ error: 'Konto gesperrt' });

        const err = await consumeCode(user, 'activationCode', 'activationCodeExpiresAt', code);
        if (err) return res.status(400).json({ error: err });

        user.isActive = true;
        await user.save();
        finishLogin(req, res, user);
    } catch (err) {
        res.status(500).json({ error: 'Internal Server Error' });
    }
});

// Login endpoint
router.post('/login', rateLimit, (req, res, next) => {
    passport.authenticate('local', async (err, user, info) => {
        try {
            if (err) return res.status(500).json({ error: 'Internal Server Error' });
            if (!user) return res.status(401).json({ error: 'Falscher Benutzername oder Passwort' });
            if (!user.isActive) return res.status(403).json({ error: 'Konto noch nicht aktiviert' });
            if (user.isBanned) return res.status(403).json({ error: 'Konto gesperrt' });

            const hasPasskeys = (await Passkey.count({ where: { UserId: user.id } })) > 0;

            if (user.totpEnabled || hasPasskeys || user.emailOtpEnabled) {
                req.session.mfaPendingUserId = user.id;
                return res.json({
                    mfaRequired: true,
                    methods: {
                        totp: user.totpEnabled,
                        passkey: hasPasskeys,
                        email: user.emailOtpEnabled
                    }
                });
            }

            finishLogin(req, res, user);
        } catch (e) {
            res.status(500).json({ error: 'Internal Server Error' });
        }
    })(req, res, next);
});

// --- MFA Login Routes ---
router.post('/login/email-otp/request', rateLimit, async (req, res) => {
    try {
        const user = await pendingUser(req);
        if (!user) return res.status(400).json({ error: 'Sitzung abgelaufen' });
        if (!user.emailOtpEnabled) return res.status(400).json({ error: 'Ungültige Anfrage' });

        const code = generateCode();
        user.emailOtpCode = code;
        user.emailOtpExpiry = new Date(Date.now() + 10 * 60000); // 10 minutes
        user.codeAttempts = 0;
        await user.save();

        await sendMail(
            user.email,
            'Dein Login-Code (2FA)',
            `Dein Login-Code lautet: ${code}\nDieser Code ist 10 Minuten gültig.`,
            `<p>Dein Login-Code lautet: <b>${code}</b></p><p>Dieser Code ist 10 Minuten gültig.</p>`
        );
        res.json({ ok: true });
    } catch (err) {
        res.status(500).json({ error: 'Fehler beim Senden' });
    }
});

router.post('/login/email-otp/verify', rateLimit, async (req, res) => {
    try {
        const code = str(req.body.code, 10);
        const user = await pendingUser(req);
        if (!user || !code) return res.status(400).json({ error: 'Sitzung abgelaufen oder Code fehlt' });
        if (!user.emailOtpEnabled) return res.status(400).json({ error: 'Ungültige Anfrage' });

        const err = await consumeCode(user, 'emailOtpCode', 'emailOtpExpiry', code);
        if (err) return res.status(400).json({ error: err });

        user.emailOtpExpiry = null;
        await user.save();

        req.session.mfaPendingUserId = null;
        finishLogin(req, res, user);
    } catch (err) {
        res.status(500).json({ error: 'Fehler' });
    }
});

router.post('/login/totp', rateLimit, async (req, res) => {
    try {
        const token = str(req.body.token, 10);
        const user = await pendingUser(req);
        if (!user || !token) return res.status(400).json({ error: 'Sitzung abgelaufen oder Token fehlt' });
        if (!user.totpEnabled) return res.status(400).json({ error: 'Ungültige Anfrage' });

        let isValid = false;
        if (user.totpSecret && totp.checkToken(token, user.totpSecret)) {
            isValid = true;
        } else {
            const totpTokens = await TotpToken.findAll({ where: { UserId: user.id } });
            for (let t of totpTokens) {
                if (totp.checkToken(token, t.secret)) {
                    isValid = true;
                    break;
                }
            }
        }

        if (!isValid) return res.status(400).json({ error: 'Ungültiger Code' });

        req.session.mfaPendingUserId = null;
        finishLogin(req, res, user);
    } catch (err) {
        res.status(500).json({ error: 'Fehler bei der MFA' });
    }
});

router.post('/login/passkey/options', rateLimit, async (req, res) => {
    try {
        const user = await pendingUser(req);
        if (!user) return res.status(400).json({ error: 'Sitzung abgelaufen' });
        const passkeys = await Passkey.findAll({ where: { UserId: user.id } });

        const options = await generateAuthenticationOptions({
            rpID: rp(req).rpID,
            allowCredentials: passkeys.map(pk => ({
                id: pk.credentialID,
                transports: pk.transports || []
            })),
            userVerification: 'preferred',
        });

        user.currentChallenge = options.challenge;
        await user.save();

        res.json(options);
    } catch (err) {
        res.status(500).json({ error: 'Fehler' });
    }
});

/** Look up a passkey by the credential id the browser sent. */
async function findPasskey(where, id) {
    if (typeof id !== 'string' || !id) return null;
    const passkeys = await Passkey.findAll({ where });
    return passkeys.find(pk => Buffer.from(pk.credentialID, 'base64url').toString('base64url') === id || pk.credentialID === id) || null;
}

async function verifyPasskey(req, passkey, expectedChallenge) {
    const { rpID, origin } = rp(req);
    const verification = await verifyAuthenticationResponse({
        response: req.body,
        expectedChallenge,
        expectedOrigin: origin,
        expectedRPID: rpID,
        credential: {
            id: passkey.credentialID,
            publicKey: new Uint8Array(passkey.credentialPublicKey),
            counter: Number(passkey.counter),
            transports: passkey.transports || undefined,
        }
    });
    if (verification.verified) {
        passkey.counter = verification.authenticationInfo.newCounter;
        await passkey.save();
    }
    return verification.verified;
}

router.post('/login/passkey/verify', rateLimit, async (req, res) => {
    try {
        const user = await pendingUser(req);
        if (!user || !user.currentChallenge) return res.status(400).json({ error: 'Sitzung abgelaufen' });

        const passkey = await findPasskey({ UserId: user.id }, req.body && req.body.id);
        if (!passkey) return res.status(400).json({ error: 'Unbekannter Passkey' });

        const challenge = user.currentChallenge;
        user.currentChallenge = null;           // one attempt per challenge
        await user.save();

        if (!(await verifyPasskey(req, passkey, challenge))) {
            return res.status(400).json({ error: 'Verifizierung fehlgeschlagen' });
        }
        req.session.mfaPendingUserId = null;
        finishLogin(req, res, user);
    } catch (err) {
        res.status(500).json({ error: 'Fehler' });
    }
});

// --- Passwordless WebAuthn ---
router.post('/login/passkey/options-passwordless', rateLimit, async (req, res) => {
    try {
        const options = await generateAuthenticationOptions({
            rpID: rp(req).rpID,
            userVerification: 'preferred',
            // No allowCredentials array to allow discoverable credentials
        });

        // Store challenge in the anonymous session
        req.session.passwordlessChallenge = options.challenge;

        res.json(options);
    } catch (err) {
        res.status(500).json({ error: 'Fehler' });
    }
});

router.post('/login/passkey/verify-passwordless', rateLimit, async (req, res) => {
    try {
        const challenge = req.session.passwordlessChallenge;
        if (!challenge) return res.status(400).json({ error: 'Sitzung abgelaufen' });
        req.session.passwordlessChallenge = null;   // one attempt per challenge

        const id = req.body && req.body.id;
        if (typeof id !== 'string' || !id) return res.status(400).json({ error: 'Unbekannter Passkey' });
        // Exact match first; passkeys from older library versions may differ in encoding
        const passkey = await findPasskey({ credentialID: id }, id) || await findPasskey({}, id);
        if (!passkey) return res.status(400).json({ error: 'Unbekannter Passkey' });

        const user = await User.findByPk(passkey.UserId);
        if (!user || !user.isActive) return res.status(403).json({ error: 'Konto nicht aktiviert' });
        if (user.isBanned) return res.status(403).json({ error: 'Konto gesperrt' });

        if (!(await verifyPasskey(req, passkey, challenge))) {
            return res.status(400).json({ error: 'Verifizierung fehlgeschlagen' });
        }
        finishLogin(req, res, user);
    } catch (err) {
        res.status(500).json({ error: 'Fehler' });
    }
});

// Password reset request
router.post('/reset-password/request', rateLimit, async (req, res) => {
    try {
        const email = str(req.body.email, 254);
        if (!email) return res.status(400).json({ error: 'E-Mail ist erforderlich.' });

        const user = await User.findOne({ where: { email } });
        if (!user || user.isBanned) {
            // Return success even if not found to prevent email scanning
            return res.json({ ok: true });
        }

        const resetCode = generateCode();
        user.resetCode = resetCode;
        user.resetCodeExpiresAt = new Date(Date.now() + 60 * 60 * 1000); // 1 hour
        user.codeAttempts = 0;
        await user.save();

        const text = `Dein Code zum Zurücksetzen deines Hochciv Passworts lautet: ${resetCode}`;
        await sendMail(user.email, 'Hochciv Passwort zurücksetzen', text, text);

        return res.json({ ok: true });
    } catch (err) {
        console.error('Reset request error', err);
        return res.status(500).json({ error: 'Internal Server Error' });
    }
});

// Password reset confirm
router.post('/reset-password/confirm', rateLimit, async (req, res) => {
    try {
        const email = str(req.body.email, 254);
        const code = str(req.body.code, 10);
        const newPassword = req.body.newPassword;
        if (!email || !code || !newPassword) {
            return res.status(400).json({ error: 'E-Mail, Code und neues Passwort werden benötigt.' });
        }
        if (!validPassword(newPassword)) {
            return res.status(400).json({ error: `Das Passwort muss mindestens ${MIN_PASSWORD_LENGTH} Zeichen lang sein.` });
        }
        const user = await User.findOne({ where: { email } });
        if (!user) {
            return res.status(400).json({ error: 'Ungültiger Code oder E-Mail.' });
        }

        const err = await consumeCode(user, 'resetCode', 'resetCodeExpiresAt', code);
        if (err) return res.status(400).json({ error: err });

        user.password_hash = await bcrypt.hash(newPassword, 10);
        user.isActive = true; // Automatically mark account as active since they proved ownership of the email
        await user.save();
        await destroyOtherSessions(sequelize, user.id);
        return res.json({ ok: true });
    } catch (err) {
        console.error('Reset confirm error', err);
        return res.status(500).json({ error: 'Internal Server Error' });
    }
});

