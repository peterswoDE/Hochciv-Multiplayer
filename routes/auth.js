// Public endpoint: which OAuth providers are enabled?
router.get('/oauth-status', async (req, res) => {
    try {
        const providers = await OAuthProvider.findAll({ where: { enabled: true } });
        const result = { google: false, discord: false };
        for (const p of providers) {
            if (p.clientId && p.clientSecret) result[p.provider] = true;
        }
        res.json(result);
    } catch (err) {
        res.json({ google: false, discord: false });
    }
});

for (const provider of ['google', 'discord']) {
    const label = provider === 'google' ? 'Google' : 'Discord';

    router.get(`/${provider}`, (req, res, next) => {
        if (!oauth.isEnabled(provider)) {
            return res.status(404).json({ error: `${label} Login ist nicht konfiguriert.` });
        }
        passport.authenticate(provider)(req, res, next);
    });

    router.get(`/${provider}/callback`, (req, res, next) => {
        if (!oauth.isEnabled(provider)) {
            return res.redirect('/client/');
        }
        passport.authenticate(provider, (err, user, info) => {
            if (err) {
                console.error(`[OAuth] ${label} Callback Error:`, err);
                return res.redirect(`/client/?error=oauth_${provider}_error`);
            }
            if (!user) {
                console.error(`[OAuth] ${label} Auth failed. Info:`, info);
                return res.redirect(`/client/?error=oauth_${provider}_failed`);
            }
            req.login(user, (loginErr) => {
                if (loginErr) {
                    console.error(`[OAuth] ${label} Login Error:`, loginErr);
                    return res.redirect(`/client/?error=oauth_${provider}_login`);
                }
                res.redirect('/client/');
            });
        })(req, res, next);
    });
}

